"""Extract the I-SPI core DDL (db/10_ispi_core.sql) from a schema-only pg_dump.

Usage: python -I extract_core_ddl.py <schema_full.sql> <out.sql>

The dump itself stays out of git (it is a full schema snapshot of a live
database). This script keeps only the objects a fresh install needs that are
NOT defined by curveRcore's calib_schema.sql (db/20_calib_schema.sql). The
object list is the result of the reachability review recorded in db/MANIFEST.md.
"""
import re, sys

KEEP = {
    ("madi_lumi_users", "projects"), ("madi_lumi_users", "project_users"),
    ("madi_lumi_users", "project_access_keys"),
    ("public", "add_project_access_key"),
    ("madi_results", "xmap_header"), ("madi_results", "xmap_standard"),
    ("madi_results", "xmap_control"), ("madi_results", "xmap_buffer"),
    ("madi_results", "xmap_sample"), ("madi_results", "xmap_antigen_family"),
    ("madi_results", "xmap_planned_visit"), ("madi_results", "xmap_users"),
    ("madi_results", "annotation_analyte"), ("madi_results", "annotation_level"),
    ("madi_results", "annotation_order"),
    ("madi_results", "curve_lookup"), ("madi_results", "source_alias"),
    ("madi_results", "calib_recalc_flag"),
    ("madi_results", "curve_lookup_unmasked"),
    ("madi_results", "sample_for_fit"), ("madi_results", "standard_for_fit"),
    ("madi_results", "blank_for_fit"), ("madi_results", "control_for_fit"),
    ("madi_results", "madi_multiplate_group_id"),
    ("madi_results", "trg_set_multiplate_group_id"),
    ("madi_results", "resolve_settings"), ("madi_results", "resolve_settings_batch"),
    ("madi_results", "calib_settings_candidates"),
}
KEEP_SCHEMAS = set()                        # both schemas come from 00_schemas.sql

src, out = sys.argv[1], sys.argv[2]
text = open(src, encoding="utf-8").read()
head = re.compile(r"^--\n-- Name: (.*?); Type: ([A-Z ]+); Schema: ([^;]+); Owner: [^\n]*\n--\n", re.M)
marks = list(head.finditer(text))
preamble = text[:marks[0].start()]
items = []
for i, m in enumerate(marks):
    body = text[m.end(): marks[i + 1].start() if i + 1 < len(marks) else len(text)]
    items.append((m.group(1), m.group(2), m.group(3), m.group(0) + body))

def first(name):                      # "tbl constraint" / "FUNCTION f(args)" / "COLUMN t.c"
    n = re.sub(r"^(TABLE|VIEW|FUNCTION|COLUMN|SCHEMA) ", "", name)
    n = n.split("(")[0].split(" ")[0]
    return n.split(".")[0]

kept_tables = {n for s, n in KEEP}
keep, dropped_fk = [], []
for name, typ, schema, chunk in items:
    if typ == "SCHEMA":
        ok = name in KEEP_SCHEMAS
    elif typ in ("SEQUENCE", "SEQUENCE OWNED BY"):
        ok = None                     # decided below, once the other kept objects are known
    else:
        ok = (schema, first(name)) in KEEP
    if ok and typ == "FK CONSTRAINT":
        ref = re.search(r"REFERENCES ([a-z_]+)\.([a-z_]+)", chunk)
        if ref and (ref.group(1), ref.group(2)) not in KEEP:
            dropped_fk.append(name); ok = False
    if ok is None or ok:
        keep.append((name, typ, schema, chunk))

# A sequence is kept only if a kept object uses it: an identity / OWNED BY clause
# naming a kept table, or a nextval('<schema>.<sequence>') in a kept object.
SEQ_TABLE = re.compile(r"(?:ALTER TABLE|OWNED BY) (?:ONLY )?([a-z_]+)\.([a-z_]+)")
others = "".join(c for n, t, sc, c in keep if t not in ("SEQUENCE", "SEQUENCE OWNED BY"))
def seq_used(name, schema, chunk):
    m = SEQ_TABLE.search(chunk)
    if m:
        return (m.group(1), m.group(2)) in KEEP
    return ("%s.%s'" % (schema, name)) in others
keep = [k for k in keep
        if k[1] not in ("SEQUENCE", "SEQUENCE OWNED BY") or seq_used(k[0], k[2], k[3])]

pre = "\n".join(l for l in preamble.splitlines() if l.startswith("SET ") or l.startswith("SELECT pg_catalog"))
hdr = ("-- =============================================================================\n"
       "-- 10_ispi_core.sql -- I-SPI core schema: users/projects, raw assay tables,\n"
       "-- curve registry, settings-cascade functions and the *_for_fit views.\n"
       "-- GENERATED by db/tools/extract_core_ddl.py from a schema-only pg_dump of the\n"
       "-- production database; do not edit by hand. See db/MANIFEST.md.\n"
       "-- =============================================================================\n\n")
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write(hdr + pre + "\n\n" + "".join(c for _, _, _, c in keep).rstrip() + "\n")
found = {(sc, first(n)) for n, t, sc, _ in keep}
print("kept items:", len(keep))
print("missing from dump:", sorted(KEEP - found))
print("dropped FKs to non-kept tables:", dropped_fk)
